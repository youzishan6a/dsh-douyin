/** 用 esbuild 把 src 打成单文件 ESM；playwright-core 保持外部依赖，因为它要在运行时定位本机浏览器。 */

import { build } from 'esbuild';

await build({
  entryPoints: ['src/index.js'],
  outfile: 'lib/index.js',
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node20',
  external: ['playwright-core'],
  legalComments: 'none',
  sourcemap: false,
  banner: { js: '// dsh-douyin — generated by scripts/build.mjs, edit src/ instead.' },
  logLevel: 'info',
});
