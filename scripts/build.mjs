/**
 * 构建两个产物：
 * 1. lib/index.js —— 宿主侧 ESM 单文件（playwright-core 保持外部依赖）；
 * 2. lib/client.js —— 设置页按钮的浏览器端 CJS，按 dsh 的 ModuleLoader 约定包装。
 */

import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { build } from 'esbuild';

const pkg = JSON.parse(readFileSync('package.json', 'utf8'));

await build({
  entryPoints: ['src/index.js'],
  outfile: 'lib/index.js',
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node20',
  external: ['playwright-core'],
  legalComments: 'none',
  sourcemap: false,
  banner: { js: `// dsh-douyin ${pkg.version} — generated by scripts/build.mjs, edit src/ instead.` },
  logLevel: 'info',
});

const client = await build({
  entryPoints: ['src-client/index.js'],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: ['chrome100'],
  external: ['react', 'react-dom', 'react/jsx-runtime'],
  write: false,
  minify: false,
  legalComments: 'none',
  define: { __DSH_DOUYIN_VERSION__: JSON.stringify(pkg.version) },
});

const bundled = client.outputFiles?.[0]?.text;
if (!bundled) throw new Error('esbuild 没有产出客户端 bundle');

const wrapped = `window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${bundled}
    return module.exports;
  }
});
`;

mkdirSync('lib', { recursive: true });
writeFileSync('lib/client.js', wrapped, 'utf8');
console.log(`Wrote lib/client.js (${Buffer.byteLength(wrapped)} bytes)`);
